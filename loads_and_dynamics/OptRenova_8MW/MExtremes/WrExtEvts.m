      function WrEEXLS
      % Write the extreme events to an Excel file.

         % Use <object>.methods and/or <object>.methodsview to see a list of
         % possible methods for a given object.  For example:
         %
         % SheetObj.methods;
         %
         % You can halt your program in the debugger and enter those
         % commands to test methods for an object.


         % Set up the name of the Excel file.  Delete the file if it already exists

      XLSfile     = [  outputFileRoot, '_EEvts.', XLStype ];
     % FullXLSfile = [ pwd, filesep, XLSfile ];
      XlRealFmt   = strrep( sprintf( RealFmt, 0 ), 'e', 'E' );

      fprintf( '  Writing extreme events to "%s".\n', XLSfile );

      DelFile( XLSfile );


         % Turn off warnings regarding adding sheets to the workbook.

      warning off MATLAB:xlswrite:AddSheet


         % Generate one sheet for each extreme-event table.

      for Tab=1:size( EEvTable, 2 )

         Sheet = EEvTable(Tab).Name;

         NumEEvChans  = size( EEvTable(Tab).Chans   , 2 );
         NumInfoChans = size( EEvTable(Tab).InfChans, 2 );
         TotEEvChans  = NumEEvChans + NumInfoChans;

         fprintf( '    Sheet: "%s"\n', Sheet );

         Info = cell( 2*NumEEvChans+5, TotEEvChans+5 );

         Info{1,1} = sprintf( 'This extreme-event table for %s was generated by %s on %s at %02d:%02d:%02d.', Sheet, ProgName, Date, uint8( DateTime(4:6) ) );

         if ( FindPeaks )
            Info{3,1} = sprintf( 'The peak finder was used to adjust the peaks and valleys.' );
         else
            Info{3,1} = sprintf( 'The peak finder was not used to adjust the peaks and valleys.' );
         end % if

         for Chan=1:NumEEvChans
            Info{5,Chan+5} = FileInfo.ChanNames{ EEvTable(Tab).Chans(Chan) };
         end % for Chan

         for Chan=1:NumInfoChans
            Info{5,Chan+NumEEvChans+5} = FileInfo.ChanNames{ EEvTable(Tab).InfChans(Chan) };
         end % for Chan


         if ( FileInfo.HaveUnits )

            Info{6,1} = 'Parameter';
            Info{6,2} = 'Type';
            Info{6,3} = 'File Name';
            Info{6,4} = 'DLC Name';
            Info{6,5} = 'Calculated Extreme';
            FirstData = 7;

            for Chan=1:NumEEvChans
               Info{6,Chan+5} = FileInfo.Units{ EEvTable(Tab).Chans(Chan) };
            end % for Chan

            for Chan=1:NumInfoChans
               Info{6,Chan+NumEEvChans+5} = FileInfo.Units{ EEvTable(Tab).InfChans(Chan) };
            end % for Chan

         else

            Info{5,1} = 'Parameter';
            Info{5,2} = 'Type';
            Info{5,3} = 'File Name';
            Info{5,4} = 'DLC Name';
            Info{5,5} = 'Calculated Extreme';
            FirstData = 6;

         end % if ( FileInfo.HaveUnits )

         for Chan=1:NumEEvChans

            Info{FirstData+2*Chan-2,1} = FileInfo.ChanNames{EEvTable(Tab).Chans(Chan)};
            Info{FirstData+2*Chan-1,1} = FileInfo.ChanNames{EEvTable(Tab).Chans(Chan)};

            Info{FirstData+2*Chan-2,2} = 'Minimum';
            Info{FirstData+2*Chan-1,2} = 'Maximum';

            Info{FirstData+2*Chan-2,3} = EEvTable(Tab).Chan(Chan).MinFilename{1};
            Info{FirstData+2*Chan-1,3} = EEvTable(Tab).Chan(Chan).MaxFilename{1};
            
            Info{FirstData+2*Chan-2,4} = EEvTable(Tab).Chan(Chan).MinDLCname;
            Info{FirstData+2*Chan-1,4} = EEvTable(Tab).Chan(Chan).MaxDLCname;
            Info{FirstData+2*Chan-2,5} = EEvTable(Tab).Chan(Chan).MinVal;
            Info{FirstData+2*Chan-1,5} = EEvTable(Tab).Chan(Chan).MaxVal;
            for Ch=1:TotEEvChans
               Info{FirstData+2*Chan-2,Ch+5} = EEvTable(Tab).Chan(Chan).ChanMinVals(Ch);
               Info{FirstData+2*Chan-1,Ch+5} = EEvTable(Tab).Chan(Chan).ChanMaxVals(Ch);
            end % for Ch

         end % for Chan

         xlswrite( XLSfile, Info, Sheet, 'A2' );

      end % for Tab

      %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
      
      Sheet = 'Safety Factors';

         NumEEvTableChans  = size(Settings.EETableChans,2);
        
   

         fprintf( '    Sheet: "%s"\n', Sheet );

         Info = cell( FileInfo.NumDLCs, NumEEvTableChans+1 );
         Info{5,1} = 'DLC Name';
         Info{1,1} = sprintf( 'This Safety Factors table was generated by %s on %s at %02d:%02d:%02d.', ProgName, Date, uint8( DateTime(4:6) ) );


         for Chan=1:NumEEvTableChans

            Info{5,Chan+1} = FileInfo.ChanNames{Settings.EETableChans(Chan)};
         end % for Chan
      
         for DLC=1:FileInfo.NumDLCs

            Info{5+DLC,1} = FileInfo.DLCs(DLC).DLC_Name;
            for Chan=1:NumEEvTableChans
               if ( FileInfo.UserNames ) %Possible use of PSF
                  Ch = Settings.EETableChans(Chan);
                  if Ch > FileInfo.NumChans
                     PSFtype = 0;
                  else
                     PSFtype = FileInfo.PSFtype(Settings.EETableChans(Chan)); %Settings.EEChanLocs(Chan));
                  end
                  if ( PSFtype > 0 ) 
                     PSF = FileInfo.DLCs(DLC).PSF(PSFtype);
                  else
                     PSF = 1.0;
                  end
               else
                  PSF = 1.0;
               end
               Info{5+DLC,Chan+1} = PSF;
            end % Chan
         end % for DLC
        
      xlswrite( XLSfile, Info, Sheet, 'A2' );
      
      
               % Use ActiveX to format the workbook.  Start Excel and make the Excel window visible.

      ExObj         = actxserver ( 'Excel.Application' );
%DEBUG
%      ExObj.Visible = 1;
      AllBooksObj   = ExObj.Workbooks;
      WkBkObj       = AllBooksObj.Open( XLSfile );
      SheetsObj     = WkBkObj.Sheets;
      LastHeadRow   = sprintf( '%d', FirstData );


         % Delete any blank sheets.  If there nothing in the first column, delete it and try the next sheet.

      SheetObj = get( SheetsObj, 'Item', 1 );

      while ( SheetObj.Range('A1').End('xlDown').Row > 2 )
         SheetObj.Delete;
         SheetObj = get( SheetsObj, 'Item', 1 );
      end % if

      
%       SheetObj = SheetsObj.Item(SheetsObj.Count);
%          SheetObj.Activate;
% 
% 
%             % Get number of EE channels and number of sheet columns.
% 
%          NumEEChans = ( SheetObj.Range(['A',LastHeadRow]).End('xlDown'   ).Row - FirstData )/2;
%          NumCols    =   SheetObj.Range(['A',LastHeadRow]).End('xlToRight').Column;
%          
%             % Determine the Alpha designation of the last column
%          EndColChr  =   ConvertNumberColToCharCol( NumCols );
%          
%             % Make the header bold.
% 
%          RngObj = SheetObj.Range( [ 'A2:', EndColChr, LastHeadRow ] );
% 
%          RngObj.Font.Bold = true;
% 
%          RngObj = SheetObj.Range( [ 'A6:', EndColChr, LastHeadRow ] );
% 
%          RngObj.Interior.ThemeColor   = ThemeColor;
%          RngObj.Interior.TintAndShade = HeadTnS;
% 
%          RngObj = SheetObj.Range( [ 'A', sprintf('%d',FirstData), ':A', sprintf('%d',2*NumEEChans+FirstData) ] );
% 
%          RngObj.Font.Bold             = true;
%          RngObj.Interior.ThemeColor   = ThemeColor;
%          RngObj.Interior.TintAndShade = HeadTnS;
%          RngObj.Columns.AutoFit();
% 
% 
%             % Make the channel names (and units) right justified.
% 
%          RngObj = SheetObj.Range( [ 'F6:', EndColChr, LastHeadRow ] );
% 
%          RngObj.HorizontalAlignment = -4152;
      
      
      %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

         % Delete the blank sheets created by Excel, "Sheet1".

%      DelSheet1( XLSfile );




         % Format each non-empty sheet in the workbook.

      for s=1:SheetsObj.Count-1


            % Get the s'th sheet object and show it.

         SheetObj = SheetsObj.Item(s);
         SheetObj.Activate;


            % Get number of EE channels and number of sheet columns.

         NumEEChans = ( SheetObj.Range(['A',LastHeadRow]).End('xlDown'   ).Row - FirstData )/2;
         NumCols    =   SheetObj.Range(['A',LastHeadRow]).End('xlToRight').Column;
         
            % Determine the Alpha designation of the last column
         EndColChr  =   ConvertNumberColToCharCol( NumCols );
         
            % Make the header bold.

         RngObj = SheetObj.Range( [ 'A2:', EndColChr, LastHeadRow ] );

         RngObj.Font.Bold = true;

         RngObj = SheetObj.Range( [ 'A6:', EndColChr, LastHeadRow ] );

         RngObj.Interior.ThemeColor   = ThemeColor;
         RngObj.Interior.TintAndShade = HeadTnS;

         RngObj = SheetObj.Range( [ 'A', sprintf('%d',FirstData), ':C', sprintf('%d',2*NumEEChans+FirstData) ] );

         RngObj.Font.Bold             = true;
         RngObj.Interior.ThemeColor   = ThemeColor;
         RngObj.Interior.TintAndShade = HeadTnS;
         RngObj.Columns.AutoFit();


            % Make the channel names (and units) right justified.

         RngObj = SheetObj.Range( [ 'F6:', EndColChr, LastHeadRow ] );

         RngObj.HorizontalAlignment = -4152;


            % Color the "diagonal".

         for Ch=1:NumEEChans

            ColStr = ConvertNumberColToCharCol(Ch+5);
            
            BegRow = 2*Ch + FirstData - 1;
            RngObj = SheetObj.Range( [ ColStr, sprintf('%d',BegRow), ':', ColStr, sprintf('%d',BegRow+1) ] );

            RngObj.Font.Bold             = true;
            RngObj.Interior.ThemeColor   = ThemeColor;
            RngObj.Interior.TintAndShade = DiagTnS;

         end % for Ch


            % Set the number format to XlRealFmt.  Set the column width to
            % accomodate the widest column.

         RngObj = SheetObj.Range( [ 'E', sprintf('%d',FirstData+1), ':', EndColChr, sprintf('%d',FirstData+2*NumEEChans) ] );
         RngObj.cells.EntireColumn.NumberFormat = XlRealFmt;
         RngObj.cells.EntireColumn.AutoFit();

         MaxWidth = 0;

         for Ch=1:TotEEvChans
            
            ColStr = ConvertNumberColToCharCol( Ch + 5 );
            
            RngObj = SheetObj.Range( [ ColStr, '1:', ColStr, '1' ] );

            if ( RngObj.EntireColumn.ColumnWidth > MaxWidth )
               MaxWidth = RngObj.EntireColumn.ColumnWidth;
            end % if

         end % for Ch
         
         ColStr = ConvertNumberColToCharCol( TotEEvChans+5 );
         
         RngObj = SheetObj.Range( [ 'F1:', ColStr, '1' ] );
         RngObj.EntireColumn.ColumnWidth  = MaxWidth;


            % Set the column for the parameter, type, and file-name rows to autofit.

         RngObj = SheetObj.Range( 'B1:E1' );
         RngObj.cells.EntireColumn.AutoFit();


            % Select cell A1.  How can I make it the current selection?

         RngObj = SheetObj.Range( 'A1' );
         RngObj.Activate;

      end % for s


         % Make the first sheet active, save the workbook without prompting, close Excel, and delete the object.

      SheetsObj.Item(1).Activate;
      WkBkObj.Save;
      WkBkObj.Close( false );

      ExObj.Quit
      ExObj.delete

      fprintf( '  Done.\n' );
      return

   end % function WrXLS
