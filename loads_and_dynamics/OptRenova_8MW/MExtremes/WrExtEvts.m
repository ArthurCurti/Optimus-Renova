function WrExtEvts( outputFileRoot, SettingsFile, EEvTable, ProgName, Settings, FileInfo, FindPeaks, WrEEvtsTxt, RealFmt, WrEEvtsXLS, XLStype, ThemeColor, HeadTnS, DiagTnS )
% Write extreme-event tables to a file.
%
% Syntax is:  GenExtEvts( SettingsFile, EEvTable, ProgName, FileList, FileInfo, FindPeaks, WrEEvtsTxt, RealFmt, WrEEvtsXLS, XLStype )
%
% Example:
%
%     GenExtEvts( SettingsFile, EEvTable, ProgName, FileList, FileInfo, FindPeaks, WrEEvtsTxt, RealFmt, WrEEvtsXLS, XLStype )
%
% See also MExtremes, ReadEESettings


      % Get the date and time.

   DateTime = clock;
   Date     = date;


      % Write extreme-event tables.

  %SettingsRoot = GetRoot( SettingsFile );

   if ( WrEEvtsTxt )
      WrEETxt;
   end % if

   if ( WrEEvtsXLS )
      WrEEXLS;
   end % if


%===============================================================================
      function WrEETxt
      % Write the extreme events to a plain-text file.

      LongLine = 9;

      RealFmtLenS = regexp( RealFmt, '\d*', 'ignorecase', 'match', 'once' );
      RealFmtLen  = sscanf( RealFmtLenS, '%d' );
      StrFmt      = [ '%' , RealFmtLenS, 's' ];
      Dashes      = [ ' ', repmat( '-', 1, RealFmtLen ) ];
%GJH Change the following to use the longest stored filename in the EEvTable(Tab).Chan(Chan).MinFilename or EEvTable(Tab).Chan(Chan).MaxFilename
      for Tab=1:size( EEvTable, 2 )
         NumEEvChans  = size( EEvTable(Tab).Chans   , 2 );
         for Chan=1:NumEEvChans
            FileName = EEvTable(Tab).Chan(Chan).MinFilename;
            LongLine =  max( size(FileName{1}, 2 ),LongLine);
         end
      end
%       for File=1:size( FileList, 1 )
%          
%          LongLine = max( size( FileList{File}, 2 ), 9 );
%       end % for File

      TxtFile = [ outputFileRoot, '.extr' ];

      fprintf( '\n  Writing plain-text extreme-event tables to "%s".\n', TxtFile );

      fid = fopen( TxtFile, 'wt' );
      while ( fid < 0 )
         beep;
         %HdlDgl = warndlg( sprintf( 'Please close "%s" if it is open in another program such as Excel.', DataFileName ), 'File Locked!', 'replace' );
         choice = questdlg( sprintf( '  Could not open "%s" for writing.', TxtFile), 'File Locked!', 'Retry','Abort','Retry' );
         %uiwait( HdlDgl );
         switch (choice)
            case 'Retry'     
               fid = fopen( DataFileName, 'wt' );
            case 'Abort'
               error('Aborting MExtremes,  could not open "%s" for writing.', TxtFile);
         end
      end % while


      DateTime = clock;

      fprintf( fid, '\nThese extreme-event tables were generated by %s on %s at %02d:%02d:%02d.\n', ProgName, date, uint8( DateTime(4:6) ) );

      if ( FindPeaks )
         fprintf( fid, '\nThe peak finder was used to adjust the peaks and valleys.\n' );
      else
         fprintf( fid, '\nThe peak finder was not used to adjust the peaks and valleys.\n' );
      end % if


         % Generate the requested tables.

      for Tab=1:size( EEvTable, 2 )

         fprintf( fid, '\n\nExtreme events for %s:\n\n', EEvTable(Tab).Name );

         NumEEvChans  = size( EEvTable(Tab).Chans   , 2 );
         NumInfoChans = size( EEvTable(Tab).InfChans, 2 );
         TotEEvChans  = NumEEvChans + NumInfoChans;


            % Generate the header.

         if ( FileInfo.HaveUnits )
            Fmt = [ '                     ', repmat( ' ', 1, LongLine+2 ), repmat( [ ' ', StrFmt ], 1, TotEEvChans ), '\n' ];
            fprintf( fid, Fmt, FileInfo.ChanNames{ [ EEvTable(Tab).Chans, EEvTable(Tab).InfChans ] } );
            Fmt = [ '  Parameter   Type     File Name', repmat( ' ', 1, LongLine-9 ), repmat( [ ' ', StrFmt ], 1, TotEEvChans ), '\n' ];
            fprintf( fid, Fmt, FileInfo.Units    { [ EEvTable(Tab).Chans, EEvTable(Tab).InfChans ] } );
         else
            Fmt = [ '  Parameter   Type     File Name', repmat( ' ', 1, LongLine-9 ), repmat( [ ' ', StrFmt ], 1, TotEEvChans ), '\n' ];
            fprintf( fid, Fmt, FileInfo.ChanNames{ [ EEvTable(Tab).Chans, EEvTable(Tab).InfChans ] } );
         end % if

         Fmt = [ '  ---------   ----     ---------', repmat( ' ', 1, LongLine-9 ), repmat( Dashes, 1, TotEEvChans ), '\n' ];
         fprintf( fid, Fmt );

         Fmt = [ '  %-10s  %-7s  %-', sprintf( '%d', LongLine ), 's', repmat( [ ' ', RealFmt ], 1, TotEEvChans ), '\n' ];

         for Chan=1:NumEEvChans

            FileName = EEvTable(Tab).Chan(Chan).MinFilename;
            fprintf( fid, Fmt, FileInfo.ChanNames{EEvTable(Tab).Chans(Chan)}, 'Minimum', FileName{1}, EEvTable(Tab).Chan(Chan).ChanMinVals );

            FileName = EEvTable(Tab).Chan(Chan).MaxFilename;
            fprintf( fid, Fmt, FileInfo.ChanNames{EEvTable(Tab).Chans(Chan)}, 'Maximum', FileName{1}, EEvTable(Tab).Chan(Chan).ChanMaxVals );

         end % for Chan

      end % for Tab

      fclose( fid );

      return

      end % function WrEETxt
